# Politique de confidentialité — CorsairConnect

Dernière mise à jour : juillet 2026

## Quelles données sont collectées ?
Lorsque vous remplissez le formulaire sur ce site, nous collectons votre prénom, votre adresse email et votre numéro de téléphone.

## Pourquoi ces données sont-elles collectées ?
Ces informations sont utilisées uniquement pour :
- vous envoyer les vidéos de présentation demandées
- vous recontacter par téléphone pour un suivi personnalisé sur le projet CorsairConnect

## Qui a accès à ces données ?
Vos données ne sont jamais vendues, louées ou transmises à des tiers à des fins commerciales.

## Combien de temps sont-elles conservées ?
Vos données sont conservées le temps nécessaire au suivi de votre demande, et supprimées sur simple demande de votre part.

## Vos droits
Conformément au RGPD, vous disposez d'un droit d'accès, de rectification et de suppression de vos données. Pour exercer ce droit, contactez-nous.

